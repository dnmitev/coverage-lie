// Benchmark: no checker vs TypeScript 6 checker vs TypeScript 7 native checker.
// The demo is tiny, so we clone its src/test into N modules to get a realistic mutant count.
// Usage: node bench/run.mjs [copies...]   e.g. node bench/run.mjs 1 10 30
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const demo = path.resolve(import.meta.dirname, '..');
const copies = process.argv.slice(2).map(Number);
if (copies.length === 0) copies.push(1, 10, 30);

const scenarios = {
  'no checker': {},
  'TS 6 checker': { checkers: ['typescript'] },
  'TS 7 native checker': { checkers: ['typescript'], typescriptChecker: { experimentalNativePreview: true } },
};

function makeWorkspace(n) {
  const dir = mkdtempSync(path.join(tmpdir(), `stryker-bench-${n}-`));
  for (let i = 0; i < n; i++) {
    cpSync(path.join(demo, 'src'), path.join(dir, 'src', `m${i}`), { recursive: true });
    mkdirSync(path.join(dir, 'test', `m${i}`), { recursive: true });
    for (const file of readdirSync(path.join(demo, 'test'))) {
      const content = readFileSync(path.join(demo, 'test', file), 'utf8').replaceAll("'../src/", `'../../src/m${i}/`);
      writeFileSync(path.join(dir, 'test', `m${i}`, file), content);
    }
  }
  for (const file of ['package.json', 'tsconfig.json', 'vitest.config.ts']) cpSync(path.join(demo, file), path.join(dir, file));
  symlinkSync(path.join(demo, 'node_modules'), path.join(dir, 'node_modules'));
  return dir;
}

function run(dir, extra) {
  const config = {
    testRunner: 'vitest',
    mutate: ['src/**/*.ts'],
    reporters: ['json'],
    tsconfigFile: 'tsconfig.json',
    concurrency: 4,
    ...extra,
  };
  writeFileSync(path.join(dir, 'stryker.bench.json'), JSON.stringify(config));
  const start = performance.now();
  execFileSync('npx', ['stryker', 'run', 'stryker.bench.json'], { cwd: dir, stdio: 'ignore' });
  const seconds = (performance.now() - start) / 1000;
  const report = JSON.parse(readFileSync(path.join(dir, 'reports/mutation/mutation.json'), 'utf8'));
  const mutants = Object.values(report.files).flatMap((f) => f.mutants);
  const count = (status) => mutants.filter((m) => m.status === status).length;
  return { seconds, mutants: mutants.length, compileErrors: count('CompileError'), survived: count('Survived') };
}

const rows = [];
for (const n of copies) {
  const dir = makeWorkspace(n);
  try {
    for (const [name, extra] of Object.entries(scenarios)) {
      const r = run(dir, extra);
      rows.push(`| ${n} | ${r.mutants} | ${name} | ${r.seconds.toFixed(1)} s | ${r.compileErrors} | ${r.survived} |`);
      console.log(rows.at(-1));
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const results = `# Checker benchmark

Generated by \`node bench/run.mjs ${copies.join(' ')}\` on ${new Date().toISOString().slice(0, 10)},
Node ${process.version}, ${process.platform}/${process.arch}, concurrency 4.
Workload: the demo's src + tests cloned N times (synthetic, for scale only).

| Copies | Mutants | Scenario | Wall time | Compile errors | Survived |
|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(path.join(import.meta.dirname, 'RESULTS.md'), results);
console.log('\nWritten bench/RESULTS.md');
